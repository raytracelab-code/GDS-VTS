"""Build-time Windows version resource for both PyInstaller specs.

Reads app/version.py (single source), stamps the edition (Modern vs Legacy
Compatibility) and the git commit, and writes a PyInstaller VSVersionInfo file
into the build work folder. Never imported by the application at runtime.
"""
from pathlib import Path
import re
import subprocess


def _version(root):
    text = (Path(root)/'app'/'version.py').read_text(encoding='utf-8')
    return re.search(r"__version__\s*=\s*'([^']+)'", text).group(1), re.search(r"STAGE\s*=\s*'([^']+)'", text).group(1)


def _commit(root):
    try:
        sha = subprocess.run(['git', 'rev-parse', '--short', 'HEAD'], cwd=str(root), capture_output=True, text=True, timeout=10).stdout.strip()
        dirty = subprocess.run(['git', 'status', '--porcelain', '--untracked-files=no'], cwd=str(root), capture_output=True, text=True, timeout=10).stdout.strip()
        return (sha or 'unknown') + ('+uncommitted' if dirty else '')
    except (OSError, subprocess.SubprocessError):
        return 'unknown'


def write_version_info(root, edition, target):
    version, stage = _version(root)
    parts = [int(p) for p in version.split('.')][:3] + [0]
    commit = _commit(root)
    product = f'{version} {stage} · {edition} · {commit}'
    description = f'GDS VTS ({edition})'
    content = f"""# Generated by packaging/versioning.py — do not edit.
VSVersionInfo(
 ffi=FixedFileInfo(filevers={tuple(parts)},prodvers={tuple(parts)},mask=0x3f,flags=0x0,OS=0x40004,fileType=0x1,subtype=0x0,date=(0,0)),
 kids=[StringFileInfo([StringTable('040904B0',[
  StringStruct('CompanyName','GDS'),
  StringStruct('ProductName','GDS VTS'),
  StringStruct('FileDescription',{description!r}),
  StringStruct('InternalName','GDS VTS'),
  StringStruct('OriginalFilename','GDS VTS.exe'),
  StringStruct('FileVersion',{'.'.join(map(str, parts))!r}),
  StringStruct('ProductVersion',{product!r}),
  StringStruct('Comments','Edition: {edition}. Development build; not hardware- or cross-OS-accepted.')
 ])]),VarFileInfo([VarStruct('Translation',[1033,1200])])]
)
"""
    target = Path(target); target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding='utf-8')
    (target.parent/'BUILD_INFO.txt').write_text(f'GDS VTS {version} ({stage})\nEdition: {edition}\nCommit: {commit}\n', encoding='utf-8')
    return str(target)
